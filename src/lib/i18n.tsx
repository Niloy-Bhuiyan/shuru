export type StringKey = keyof (typeof STRINGS)["en"];

type LangContextValue = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: StringKey) => string;
};

const LangContext = createContext<LangContextValue>({
  lang: "en",
  setLang: () => {},
  t: (k) => STRINGS.en[k] ?? k,
});

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  // Hydrate: localStorage first (instant, avoids a flash), then let a saved
  // profile.language_pref win so the choice follows the user across devices.
  useEffect(() => {
    let cancelled = false;
    try {
      const stored = window.localStorage.getItem("shuru.lang");
      if (stored === "bn" || stored === "en") setLangState(stored);
    } catch {
      /* storage unavailable — ignore */
    }
    (async () => {
      try {
        const p = await getProfile();
        const pref = p?.language_pref;
        if (!cancelled && (pref === "bn" || pref === "en")) {
          setLangState(pref);
          try {
            window.localStorage.setItem("shuru.lang", pref);
          } catch {
            /* ignore */
          }
        }
      } catch {
        /* no profile / not signed in — localStorage stands */
      }
    })();
    return () => {
      cancelled = true;
    };
  }, []);

  // One source of truth: every toggle writes BOTH localStorage and the
  // profile (when one exists), so header and settings can never disagree.
  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      window.localStorage.setItem("shuru.lang", l);
    } catch {
      /* ignore */
    }
    void (async () => {
      try {
        const p = await getProfile();
        if (p && p.language_pref !== l) {
          await saveProfile({ ...p, language_pref: l });
        }
      } catch {
        /* persistence is best-effort; localStorage already holds the choice */
      }
    })();
  };

  const t = (key: StringKey): string =>
    (STRINGS[lang] as Record<string, string>)[key] ?? STRINGS.en[key] ?? key;

  return (
    <LangContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LangContext.Provider>
  );
}

export function useLang() {
  return useContext(LangContext);
}
